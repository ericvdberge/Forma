namespace Forma.Infrastructure.Storage;

/// <summary>Keeps assets as plain files under one root folder (<c>Assets:Path</c>).</summary>
public class FileSystemAssetStorage(string rootPath) : IAssetStorage
{
    private readonly string _rootPath = Path.GetFullPath(rootPath);

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken = default)
    {
        var path = Resolve(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken = default)
    {
        var path = Resolve(key);
        Stream? stream = File.Exists(path)
            ? new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 81920, useAsync: true)
            : null;
        return Task.FromResult(stream);
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken = default)
    {
        File.Delete(Resolve(key));
        return Task.CompletedTask;
    }

    // Keys are generated by the API, but never let one point outside the root folder.
    private string Resolve(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_rootPath, key));
        if (!path.StartsWith(_rootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal))
        {
            throw new ArgumentException($"Asset key '{key}' is outside the assets folder.", nameof(key));
        }

        return path;
    }
}
